from __future__ import annotations

import json
import re
from pathlib import Path

import scripts.generate_api_docs as generate_api_docs

REPO_ROOT = Path(__file__).resolve().parents[2]


def _discover(tmp_path: Path, modules: dict[str, str], operations: dict, fields=None):
    for name, source in modules.items():
        (tmp_path / "handlers" / name).parent.mkdir(parents=True, exist_ok=True)
        (tmp_path / "handlers" / name).write_text(source, encoding="utf-8")
    paths = {
        route: methods if isinstance(methods, dict) else {m: {"summary": route} for m in methods}
        for route, methods in operations.items()
    }
    (tmp_path / "openapi.json").write_text(json.dumps({"paths": paths}), encoding="utf-8")
    groups, omitted = generate_api_docs.discover_endpoints(
        tmp_path / "handlers", tmp_path / "openapi.json"
    )
    fields = fields or ("method", "path", "description")
    return [tuple(getattr(e, f) for f in fields) for g in groups for e in g.endpoints], omitted


def test_nested_routes_are_found_statically_with_the_spec_verbs(tmp_path) -> None:
    source = (
        "import module_that_is_not_installed\n\n\nclass GustoHandler:\n"
        '    ROUTES = ["/api/v1/gusto/status", "/api/v1/gusto/connect", "/api/v1/gusto/x"]\n'
        '    POST_ROUTES = ["/api/v1/gusto/x"]\n'
    )
    hidden = 'class HiddenHandler:\n    ROUTES = ["/api/v1/gusto/status"]\n'
    listed, omitted = _discover(
        tmp_path,
        {"accounting/gusto.py": source, "accounting/_hidden.py": hidden},
        {"/api/v1/gusto/status": ["get"], "/api/v1/gusto/connect": ["post"]},
    )

    assert [(method, path) for method, path, _ in listed] == [
        ("GET", "/api/v1/gusto/status"),
        ("POST", "/api/v1/gusto/connect"),
    ]
    assert omitted == 1


def test_docstring_endpoints_keep_only_verbs_the_spec_serves(tmp_path) -> None:
    source = (
        '"""A2A handlers.\n\nEndpoints:\n- GET /api/v1/a2a/tasks/:id - Get task status\n'
        "- DELETE /api/v1/a2a/tasks/:id - Cancel task\n"
        '- GET /api/v1/a2a/tasks/:id/stream - Stream task\n"""\n'
    )
    listed, omitted = _discover(
        tmp_path, {"tasks/a2a.py": source}, {"/api/v1/a2a/tasks/{task_id}": ["get"]}
    )

    assert listed == [("GET", "/api/v1/a2a/tasks/:id", "Get task status")]
    assert omitted == 2


def test_named_and_wildcard_routes_resolve_and_computed_routes_warn(tmp_path, capsys) -> None:
    routes = '["/api/v1/debates", "/api/v1/debates/", "/api/v1/debates/*/pause"]'
    modules = {
        "debates/routing.py": f"ROUTES = {routes}\n",
        "debates/handler.py": '"""Debates.\n\nEndpoints:\n- GET /api/debates - List\n"""\n'
        "from .routing import ROUTES\n\n\nclass DebatesHandler:\n    ROUTES = ROUTES\n",
        "debates/computed.py": "class ComputedHandler:\n    ROUTES = build_routes()\n",
    }
    operations = {
        "/api/debates": ["get"],
        "/api/v1/debates": ["get"],
        "/api/v1/debates/{id}/pause": ["post"],
    }
    listed, omitted = _discover(tmp_path, modules, operations)

    assert [(m, p) for m, p, _ in listed] == [
        ("GET", "/api/debates"),
        ("GET", "/api/v1/debates"),
        ("POST", "/api/v1/debates/*/pause"),
    ]
    assert omitted == 0
    assert "ComputedHandler" in capsys.readouterr().err


def test_auth_badge_needs_credentialed_security_and_flags_undeclared(tmp_path) -> None:
    source = 'class AuthHandler:\n    ROUTES = ["/a", "/b", "/c", "/d"]\n'
    operations = {
        "/a": {"get": {"security": [{}]}},
        "/b": {"get": {"security": [{"bearerAuth": []}]}},
        "/c": {"get": {"security": [{}, {"bearerAuth": []}]}},
        "/d": {"get": {"x-autogenerated": True}},
    }
    listed, _ = _discover(tmp_path, {"auth.py": source}, operations, ("path", "auth_required"))

    assert listed == [("/a", False), ("/b", True), ("/c", False), ("/d", None)]


def test_groups_are_named_by_module_path_with_unique_anchors(tmp_path) -> None:
    source = 'class UsageMeteringHandler:\n    ROUTES = ["/api/v1/billing/usage"]\n'
    modules = {"billing/usage_metering.py": source, "billing/subscriptions.py": source}
    _discover(tmp_path, modules, {"/api/v1/billing/usage": ["get"]})
    groups, _ = generate_api_docs.discover_endpoints(
        tmp_path / "handlers", tmp_path / "openapi.json"
    )
    toc = re.findall(r"^- \[.*\]\(#(.*)\)$", generate_api_docs.generate_markdown(groups), re.M)

    assert [g.name for g in groups] == [
        "UsageMetering (billing/subscriptions.py)",
        "UsageMetering (billing/usage_metering.py)",
    ]
    assert toc == ["usagemetering-billingsubscriptionspy", "usagemetering-billingusage_meteringpy"]


def test_committed_endpoint_docs_list_no_phantom_verbs() -> None:
    spec = generate_api_docs.load_spec_operations(REPO_ROOT / "docs/api/openapi.json")
    docs = (REPO_ROOT / "docs/API_ENDPOINTS.md").read_text(encoding="utf-8")
    listed = re.findall(r"^### `([A-Z]+)` `([^`]+)`", docs, re.MULTILINE)
    toc = re.findall(r"^- \[.*\]\(#(.*)\)$", docs, re.MULTILINE)

    phantom = [
        f"{m} {p}" for m, p in listed if m not in spec.get(generate_api_docs.normalize_path(p), {})
    ]

    assert listed
    assert phantom == []
    assert len(toc) == len(set(toc))

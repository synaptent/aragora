def test_handler_routes_supplement_bounds_verb_derivation_to_single_route(monkeypatch) -> None:
    """A multi-route handler must NOT get its class-level verb union per path.

    SandboxHandler-style: the class overrides handle/handle_post/handle_put/
    handle_delete, but each verb belongs to a different ROUTES path. Applying
    the full set to every path would advertise nonexistent operations, so
    multi-route handlers fall back to the per-path segment heuristic.
    """
    import sys
    import types

    class SandboxStyleHandler:
        ROUTES = [
            "/api/v1/sandbox-style/execute",
            "/api/v1/sandbox-style/config",
            "/api/v1/sandbox-style/pool/status",
        ]

        def handle(self, path, query_params, handler):
            return None

        def handle_post(self, path, query_params, handler):
            return None

        def handle_put(self, path, query_params, handler):
            return None

        def handle_delete(self, path, query_params, handler):
            return None

    fake_registry = types.SimpleNamespace(HANDLER_REGISTRY=[("_dummy", SandboxStyleHandler)])
    monkeypatch.setitem(sys.modules, "aragora.server.handler_registry", fake_registry)

    supplement = generate_openapi._collect_handler_routes_supplement({})

    # Per-path heuristic, not the class verb union {get,post,put,delete}
    assert set(supplement["/api/v1/sandbox-style/execute"]) == {"post"}
    assert set(supplement["/api/v1/sandbox-style/config"]) == {"get"}
    assert set(supplement["/api/v1/sandbox-style/pool/status"]) == {"get"}


def test_handler_routes_supplement_no_verb_union_for_lone_uncovered_route(monkeypatch) -> None:
    """Class verbs must be bounded by ALL declared generic routes, not just uncovered ones.

    EmailWebhookHandler-style regression (PR #9332 P2 dissent): the handler
    declares several generic ROUTES; all but one are already covered by the
    spec. The lone uncovered route must NOT inherit the class verb union
    (GET from handle() serving /status + POST from handle_post() serving the
    webhook) — it falls back to the per-path segment heuristic instead.
    """
    import sys
    import types

    class EmailStyleHandler:
        ROUTES = [
            "/api/v1/email-style/status",
            "/api/v1/email-style/webhook/mailgun",
        ]

        def handle(self, path, query_params, handler):
            return None  # serves GET /status only

        def handle_post(self, path, query_params, handler):
            return None  # serves POST /webhook/mailgun only

    fake_registry = types.SimpleNamespace(HANDLER_REGISTRY=[("_dummy", EmailStyleHandler)])
    monkeypatch.setitem(sys.modules, "aragora.server.handler_registry", fake_registry)

    existing = {"/api/v1/email-style/status": {"get": {"summary": "documented"}}}
    supplement = generate_openapi._collect_handler_routes_supplement(existing)

    # Segment heuristic (mailgun -> POST), never the class union {get, post}:
    # GET /webhook/mailgun would 404 at runtime (handle() ignores that path).
    assert set(supplement["/api/v1/email-style/webhook/mailgun"]) == {"post"}


def test_filter_internal_paths_drops_internal_families_from_any_tier() -> None:
    """The internal-route policy applies to the final path set, every tier.

    PR #9332 P2 dissent regression: Tier-1/2/3 outputs (canonical registry,
    @api_endpoint decorators, AST scan) bypassed the policy, publishing
    /api/control-plane/* and /api/v1/sme/* into the public spec — invisible
    to the route-coverage gate, which excludes internal prefixes from both
    sides of its comparison.
    """
    paths = {
        "/api/v1/debates": {"get": {"summary": "public"}},
        "/api/v1/control-plane/audit": {"get": {"summary": "internal"}},
        # Unversioned form must be caught via comparison-key normalization
        # (/api/ -> /api/v1/), exactly as dispatch and the gate normalize it.
        "/api/control-plane/queue/metrics": {"get": {"summary": "internal"}},
        "/api/v1/sme/onboarding": {"post": {"summary": "internal"}},
        "/api/v1/admin/emergency/lockdown": {"post": {"summary": "internal"}},
    }

    filtered = generate_openapi._filter_internal_paths(paths)

    assert set(filtered) == {"/api/v1/debates"}


def test_handler_routes_supplement_uses_explicit_routes_method_verbs(monkeypatch) -> None:
    """Explicit routes() declarations beat verb inference (P2 on #9360).

    Dispatch-based handlers like SSOHandler declare served verbs only via a
    routes() method returning (METHOD, path, name) tuples; their static
    ROUTES list is method-less. Without reading routes(), POST login/callback
    operations were documented as GET-only.
    """
    import sys
    import types

    class DummySSOHandler:
        """Dummy SSO-style handler declaring verbs via routes()."""

        ROUTES = [
            "/api/v1/dummy-sso/login",
            "/api/v1/dummy-sso/status",
        ]

        def __init__(self) -> None:
            raise AssertionError("spec generation must not construct handlers")

        def routes(self) -> list[tuple[str, str, str]]:
            return [
                ("GET", "/api/v1/dummy-sso/login", "handle_login"),
                ("POST", "/api/v1/dummy-sso/login", "handle_login"),
                ("GET", "/api/v1/dummy-sso/status", "handle_status"),
            ]

    fake_registry = types.SimpleNamespace(HANDLER_REGISTRY=[("_dummy_sso", DummySSOHandler)])
    monkeypatch.setitem(sys.modules, "aragora.server.handler_registry", fake_registry)

    supplement = generate_openapi._collect_handler_routes_supplement({})

    login = supplement["/api/v1/dummy-sso/login"]
    assert set(login) == {"get", "post"}
    assert login["post"]["x-method-inferred"] is False
    status = supplement["/api/v1/dummy-sso/status"]
    assert set(status) == {"get"}

    # The real #9360 failure mode: an earlier tier already documented GET,
    # so the generic-ROUTES covered-path skip swallowed the declared POST.
    existing = {"/api/v1/dummy-sso/login": {"get": {"summary": "documented"}}}
    supplement = generate_openapi._collect_handler_routes_supplement(existing)

    login = supplement["/api/v1/dummy-sso/login"]
    assert set(login) == {"post"}
    assert login["post"]["x-method-inferred"] is False



def test_route_to_spec_path_converts_wildcards_and_version() -> None:
    assert (
        generate_openapi._route_to_spec_path("/api/v1/rbac/roles/*")
        == "/api/v1/rbac/roles/{role_id}"
    )
    assert generate_openapi._route_to_spec_path("/api/runs") == "/api/v1/runs"
    assert (
        generate_openapi._route_to_spec_path("/api/v1/ideas/*/edges/*")
        == "/api/v1/ideas/{idea_id}/edges/{edge_id}"
    )
    assert (
        generate_openapi._route_to_spec_path("POST /api/v1/canvas/pipeline/run")
        == "/api/v1/canvas/pipeline/run"
    )
    # /api/v2 must not be rewritten to /api/v1
    assert generate_openapi._route_to_spec_path("/api/v2/tasks/*") == "/api/v2/tasks/{task_id}"


def test_handler_routes_supplement_adds_uncovered_routes(monkeypatch) -> None:
    import sys
    import types

    class DummyHandler:
        """Dummy handler for supplement tests."""

        ROUTES = [
            "/api/v1/dummy/things",
            "/api/v1/dummy/things/*",
            "/api/v1/dummy/execute",
            "/api/v1/control-plane/internal-only",
        ]
        POST_ROUTES = ["/api/v1/dummy/submit"]

    fake_registry = types.SimpleNamespace(HANDLER_REGISTRY=[("_dummy", DummyHandler)])
    monkeypatch.setitem(sys.modules, "aragora.server.handler_registry", fake_registry)

    existing = {"/api/v1/dummy/things": {"get": {"summary": "documented"}}}
    supplement = generate_openapi._collect_handler_routes_supplement(existing)

    # Covered path is skipped; wildcard becomes a named param
    assert "/api/v1/dummy/things" not in supplement
    assert "/api/v1/dummy/things/{thing_id}" in supplement
    # Internal prefix families are never published
    assert not any(p.startswith("/api/v1/control-plane/") for p in supplement)
    # Action-verb segment infers POST; plain segments infer GET
    assert "post" in supplement["/api/v1/dummy/execute"]
    assert supplement["/api/v1/dummy/execute"]["post"]["x-method-inferred"] is True
    # Method-specific *_ROUTES carry their declared method
    assert "post" in supplement["/api/v1/dummy/submit"]
    assert supplement["/api/v1/dummy/submit"]["post"]["x-method-inferred"] is False
    # Every supplement operation is marked autogenerated + experimental
    for methods in supplement.values():
        for op in methods.values():
            assert op["x-autogenerated"] is True
            assert op["x-aragora-stability"] == "experimental"


